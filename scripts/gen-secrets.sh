#!/usr/bin/env bash
# Creates .env and secrets/* with random values. Never overwrites existing ones.
set -euo pipefail
cd "$(dirname "$0")/.."
umask 077
mkdir -p secrets

rand() { python3 -c "import secrets; print(secrets.token_urlsafe($1))"; }
mk() { [ -s "secrets/$1" ] || rand 32 > "secrets/$1"; }

mk postgres_password
mk restic_password
mk grafana_admin_password
# Lab root CA for Caddy's internal issuer. Generated here (not by Caddy) so the
# public certificate can be handed to probes and clients without ever exposing
# Caddy's data volume, which holds the private keys.
if [ ! -s secrets/lab-ca.key ]; then
  openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -sha256 \
    -days 825 -subj "/CN=ISM Lab Root CA" \
    -addext "basicConstraints=critical,CA:TRUE" \
    -addext "keyUsage=critical,keyCertSign,cRLSign" \
    -keyout secrets/lab-ca.key -out secrets/lab-ca.crt 2>/dev/null
fi

# The directory stays 0700, so on the host only its owner can open anything inside.
# The files themselves are world-readable because Compose bind-mounts them with
# their host permissions and the containers run as other users (postgres, grafana).
# That includes the lab CA key: Caddy runs with every capability dropped, so even
# as uid 0 it cannot read a 0400 file owned by another user (the CI runner is uid
# 1001). On a real host the key would be owned by a dedicated caddy user instead.
chmod 0700 secrets
chmod 0444 secrets/*

if [ ! -s .env ]; then
  cat > .env <<ENV
# Generated by scripts/gen-secrets.sh. Never commit this file.
POSTGRES_PASSWORD=$(cat secrets/postgres_password)
CRM_JWT_SECRET=$(rand 48)
CRM_ADMIN_EMAIL=admin@example.com
CRM_ADMIN_PASSWORD=Lab-$(rand 18)-9x
ENV
fi
echo "secrets ready: .env and secrets/ (git-ignored, directory mode 700)"
echo "IMPORTANT: copy secrets/restic_password somewhere safe. Without it the backups cannot be decrypted."
